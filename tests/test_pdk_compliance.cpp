// --- Part 1: Structural Tests (Standard Library) ---
void test_inverter_pdk_mapping() {
    std::cout << "[Test 1] CMOS Inverter PDK Mapping (Standard Cells)..." << std::endl;
    auto* invDef = StandardCells::StandardCellLibrary::instance().get("CMOS Inverter");
    assert(invDef != nullptr);
    const TensorBlock& block = invDef->internalBlock;
    
    bool foundN = false;
    bool foundP = false;
    for (const auto& m : block.mosfets) {
        if (m.modelName == "nfet_01v8") foundN = true;
        if (m.modelName == "pfet_01v8") foundP = true;
         assert(m.w > 0.0);
         assert(m.l > 0.0);
    }
    assert(foundN && "NMOS must use 'nfet_01v8'");
    assert(foundP && "PMOS must use 'pfet_01v8'");
    std::cout << "  Passed." << std::endl;
}

// --- Part 2: GUI Integration Tests ---
void test_gui_pdk_extraction(SchematicEditor& editor) {
    std::cout << "[Test 2] GUI Component PDK Parameter Extraction..." << std::endl;
    GridScene* scene = editor.getScene();
    scene->clear(); 

    // 1. Inductor via placeComponent
    QJsonObject lParams;
    lParams["Model"] = "spiral_ind_hq";
    lParams["W"] = "5e-6";
    lParams["Area"] = "200p"; // Area might need to be explicitly set if not default
    editor.placeComponent("Inductor", QPointF(-100, -100), 0, lParams);

    // 2. PDK NFET via placeComponent
    QJsonObject mParams;
    mParams["W"] = "10e-6";
    mParams["L"] = "0.18e-6";
    editor.placeComponent("PDK_NFET", QPointF(100, 100), 0, mParams);

    // Run Netlister
    TensorNetlist netlist = editor.toNetlist();

    // Verify Inductor
    bool foundInd = false;
    for (const auto& i : netlist.globalBlock.inductors) {
        // Since we don't know the exact name generated by placeComponent (L_0, L_1?), we check params
        if (i.model_name == "spiral_ind_hq") {
            foundInd = true;
            assert(i.model_name == "spiral_ind_hq");
            // Check approx float equality
            assert(std::abs(i.width_m - 5e-6) < 1e-9);
            assert(std::abs(i.area_m2 - 200e-12) < 1e-18);
        }
    }
    assert(foundInd && "Inductor spiral_ind_hq not extracted or params mismatch");

    // Verify NFET
    bool foundMos = false;
    for (const auto& m : netlist.globalBlock.mosfets) {
        // PDK_NFET defaults to "nfet_01v8" model unless overridden
        if (m.modelName == "nfet_01v8" || m.modelName == "nfet") {
             // We configured w=10u, l=0.18u
             if (std::abs(m.w - 10e-6) < 1e-9 && std::abs(m.l - 0.18e-6) < 1e-9) {
                 foundMos = true;
             }
        }
    }
    assert(foundMos && "MOSFET M1 not extracted or params mismatch");

    std::cout << "  Passed." << std::endl;
}

void test_gui_wire_parasitics(SchematicEditor& editor) {
    std::cout << "[Test 3] Parasitic-Aware Wire Extraction (Phase 1.5)..." << std::endl;
    GridScene* scene = editor.getScene();
    scene->clear();

    // Create a wire manualy is fine as VisualWire handles its own data usually
    QLineF line(0, 0, 100, 0); // 100 pixels long
    auto* wire = new VisualWire(line);
    wire->layer = "M3";
    wire->width_um = 2.0;
    scene->addItem(wire);

    // Run Netlister
    TensorNetlist netlist = editor.toNetlist();

    bool foundSeg = false;
    for (const auto& seg : netlist.globalBlock.wireSegments) {
        if (seg.layer == "M3") {
            foundSeg = true;
            assert(std::abs(seg.width_um - 2.0) < 1e-6);
            // 1 pixel = 0.1um in logic -> 100px = 10um
            assert(std::abs(seg.length_um - 10.0) < 1e-6);
        }
    }
    assert(foundSeg && "WireSegment not extracted or properties mismatch");
    
    // Modify wire length manually
    wire->setLine(QLineF(0, 0, 200, 0)); // 200 px = 20 um
    netlist = editor.toNetlist();
    
    bool foundRes = false;
    for (const auto& r : netlist.globalBlock.parasiticResistors) {
        if (r.name.find("R_WIRE") != std::string::npos) {
            foundRes = true;
             // R = L * r_per_um. 
             // L = 20.0. r_per_um = 0.1 (default) -> R=2.0
             assert(std::abs(r.R - 2.0) < 1e-6);
        }
    }
    assert(foundRes && "Parasitic Resistor not injected for long wire");

    std::cout << "  Passed." << std::endl;
}

void test_pdk_auditor(SchematicEditor& editor) {
    std::cout << "[Test 4] PDK Compliance Auditor Scan..." << std::endl;
    GridScene* scene = editor.getScene();
    scene->clear();

    // 1. Compliant FET
    QJsonObject nParams; nParams["Model"] = "nfet_01v8";
    editor.placeComponent("PDK_NFET", QPointF(0,0), 0, nParams);

    // 2. Non-compliant FET (Invalid Model)
    QJsonObject pParams; pParams["Model"] = "invalid_model";
    editor.placeComponent("PDK_PFET", QPointF(100,0), 0, pParams);

    // 3. Generic Resistor (No warnings expected in data-driven mode)
    editor.placeComponent("Resistor", QPointF(200,0), 0, QJsonObject());

    ComplianceReport report = PDKComplianceChecker::checkCompliance(scene);
    
    // Debug output if failure
    if (report.passed) {
        std::cout << "DEBUG: Report passed unexpectedly. ErrorCount=" << report.errorCount << std::endl;
    } else {
        std::cout << "DEBUG: Report failed. ErrorCount=" << report.errorCount << " Warnings=" << report.warningCount << std::endl;
        for(auto& v : report.violations) std::cout << " - " << v.message.toStdString() << std::endl;
    }

    assert(!report.passed);
    // Expect 1 Error (Invalid Model for PFET)
    // Expect 0 Warnings (Common Resistor)
    assert(report.errorCount == 1); 
    assert(report.warningCount == 0); 
    
    std::cout << "  Passed (Detected violations correctly)." << std::endl;
}

int main(int argc, char *argv[]) {
    // headless platform interaction
    QApplication app(argc, argv);
    
    std::cout << "=== Running GUI-integrated PDK Compliance Tests ===" << std::endl;

    test_inverter_pdk_mapping();
    
    SchematicEditor editor("pdk_test.sch");
    // Ensure we start fresh
    editor.getScene()->clear();
    
    test_gui_pdk_extraction(editor);
    test_gui_wire_parasitics(editor);
    test_pdk_auditor(editor);

    std::cout << "=== All Tests Passed ===" << std::endl;
    return 0;
}
