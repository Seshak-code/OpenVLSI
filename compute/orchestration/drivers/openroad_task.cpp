std::string OpenRoadTask::generateRCXTcl(const RCXConfig& config) {
    std::vector<std::string> script;

    script.push_back("# OpenROAD RCX Parasitic Extraction Script");
    script.push_back("# Design: " + config.designName);
    script.push_back("# Generated by AcuteSim");
    script.push_back("");

    if (!config.techLef.empty())
        script.push_back("read_lef " + config.techLef);
    for (const auto& lef : config.cellLefs)
        script.push_back("read_lef " + lef);
    script.push_back("");

    if (!config.placedRoutedDef.empty())
        script.push_back("read_def " + config.placedRoutedDef);
    script.push_back("");

    if (!config.rcxRuleFile.empty())
        script.push_back("define_process_corner -ext_model_index 0 " + config.rcxRuleFile);

    script.push_back("extract_parasitics \\");
    if (!config.rcxRuleFile.empty())
        script.push_back("    -ext_model_file " + config.rcxRuleFile + " \\");
    if (config.couplingCaps)
        script.push_back("    -coupling_threshold 0.1 \\");
    script.push_back("    -max_res 0");
    script.push_back("");

    if (std::abs(config.capFactor - 1.0) > 1e-9)
        script.push_back("adjust_extraction -cap_res " + std::to_string(config.capFactor));

    if (!config.outputSpef.empty()) {
        script.push_back("write_spef " + config.outputSpef);
        script.push_back("");
        script.push_back("puts \"PEX complete. SPEF written to: " + config.outputSpef + "\"");
    }

    script.push_back("exit");

    return joinLines(script);
}

