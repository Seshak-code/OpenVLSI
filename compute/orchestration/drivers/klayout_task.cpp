std::string KLayoutTask::generateGDSExportScript(const GDSExportConfig& config) {
    std::vector<std::string> script;

    script.push_back("# KLayout GDSII Export Script (Ruby)");
    script.push_back("# Input:  " + config.inputFile);
    script.push_back("# Output: " + config.outputGDS);
    script.push_back("");

    script.push_back("layout = RBA::Layout::new");
    if (!config.techFile.empty())
        script.push_back("layout.technology = \"" + config.techFile + "\"");
    script.push_back("layout.read(\"" + config.inputFile + "\")");
    script.push_back("");

    if (!config.topCell.empty()) {
        script.push_back("top_cell = layout.cell(\"" + config.topCell + "\")");
        script.push_back("if top_cell.nil?");
        script.push_back("  raise \"Top cell '" + config.topCell + "' not found in layout\"");
        script.push_back("end");
        script.push_back("");
    }

    std::string outPath = config.outputGDS;
    if (config.compressOutput && (outPath.size() < 3 || outPath.substr(outPath.size() - 3) != ".gz"))
        outPath += ".gz";

    script.push_back("options = RBA::SaveLayoutOptions::new");
    script.push_back("options.format = \"GDS2\"");
    script.push_back("layout.write(\"" + outPath + "\", options)");
    script.push_back("");
    script.push_back("puts \"GDSII export complete: " + outPath + "\"");

    return joinLines(script);
}

