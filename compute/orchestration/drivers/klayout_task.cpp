QString KLayoutTask::generateDRCScript(const DRCConfig& config) {
    QStringList script;

    script << "# KLayout DRC Script (Ruby)";
    script << "# Generated by AcuteSim";
    script << "#";
    script << QString("# Layout: %1").arg(config.layoutFile);
    script << QString("# Rules: %1").arg(config.ruleFile);
    script << "";

    // Script header
    script << "# Load the layout";
    script << "source($layout)";
    script << "";

    // Set report output
    script << "# Configure report output";
    script << QString("report(\"%1\")").arg(
        config.outputReport.isEmpty() ? "drc_results.rpt" : config.outputReport);
    script << "";

    // Set minimum level filter
    script << "# Set severity filter";
    script << QString("# Minimum level: %1").arg(getDRCLevelFilter(config.minLevel));
    script << "";

    // Include/exclude rules
    if (!config.onlyRules.isEmpty()) {
        script << "# Run only specified rules";
        for (const QString& rule : config.onlyRules) {
            script << QString("# Include: %1").arg(rule);
        }
    }

    if (!config.excludeRules.isEmpty()) {
        script << "# Exclude specified rules";
        for (const QString& rule : config.excludeRules) {
            script << QString("# Exclude: %1").arg(rule);
        }
    }

    script << "";
    script << "# ============================================================";
    script << "# DRC RULES";
    script << "# ============================================================";
    script << "";

    // Load external rule file or inline rules
    if (!config.ruleFile.isEmpty()) {
        script << QString("# Load rule deck: %1").arg(config.ruleFile);
        script << "# source(rules_file)";
    }

    script << "";
    script << "# Example rules (placeholder - replace with actual rule deck)";
    script << "";
    script << "# Metal1 minimum width";
    script << "m1 = input(11, 0)";
    script << "m1.width(0.14.um).output(\"M1.W.1\", \"Metal1 minimum width violation\")";
    script << "";
    script << "# Metal1 minimum spacing";
    script << "m1.space(0.14.um).output(\"M1.S.1\", \"Metal1 minimum spacing violation\")";
    script << "";
    script << "# Via1 enclosure by Metal1";
    script << "v1 = input(12, 0)";
    script << "m1.enclosing(v1, 0.05.um).output(\"V1.E.1\", \"Via1 enclosure by Metal1\")";
    script << "";

    if (config.verbose) {
        script << "# Verbose mode enabled";
        script << "verbose";
    }

    script << "";
    script << "# End of DRC script";

    return script.join("\n");
}

QString KLayoutTask::generateLVSScript(const LVSConfig& config) {
    QStringList script;

    script << "# KLayout LVS Script (Ruby)";
    script << "# Generated by AcuteSim";
    script << "#";
    script << QString("# Layout: %1").arg(config.layoutFile);
    script << QString("# Schematic: %1").arg(config.schematicNetlist);
    script << QString("# Mode: %1").arg(getLVSModeOptions(config.mode));
    script << "";

    // Script header
    script << "# Load the layout";
    script << "source($layout)";
    script << "";

    // Set top cell if specified
    if (!config.topCell.isEmpty()) {
        script << QString("# Top cell: %1").arg(config.topCell);
        script << QString("top_cell(\"%1\")").arg(config.topCell);
    }

    script << "";
    script << "# Configure LVS mode";
    script << getLVSModeOptions(config.mode);
    script << "";

    // Report output
    script << "# Configure report output";
    script << QString("report_lvs(\"%1\")").arg(
        config.outputReport.isEmpty() ? "lvs_results.rpt" : config.outputReport);
    script << "";

    script << "# ============================================================";
    script << "# DEVICE EXTRACTION RULES";
    script << "# ============================================================";
    script << "";

    // Layer definitions (placeholder)
    script << "# Layer definitions";
    script << "nwell = input(1, 0)";
    script << "active = input(2, 0)";
    script << "poly = input(3, 0)";
    script << "nplus = input(4, 0)";
    script << "pplus = input(5, 0)";
    script << "contact = input(6, 0)";
    script << "metal1 = input(11, 0)";
    script << "";

    script << "# Device extraction";
    script << "# NMOS extraction";
    script << "nmos_gate = poly & active - nwell";
    script << "extract_devices(mos4(\"NMOS\"), { \"SD\" => nplus, \"G\" => nmos_gate, \"W\" => nwell })";
    script << "";
    script << "# PMOS extraction";
    script << "pmos_gate = poly & active & nwell";
    script << "extract_devices(mos4(\"PMOS\"), { \"SD\" => pplus, \"G\" => pmos_gate, \"W\" => nwell })";
    script << "";

    script << "# ============================================================";
    script << "# CONNECTIVITY";
    script << "# ============================================================";
    script << "";
    script << "# Connect layers";
    script << "connect(active, contact)";
    script << "connect(poly, contact)";
    script << "connect(contact, metal1)";
    script << "";

    script << "# ============================================================";
    script << "# SCHEMATIC COMPARISON";
    script << "# ============================================================";
    script << "";
    script << QString("# Reference netlist: %1").arg(config.schematicNetlist);
    script << "schematic(source.netlist)";
    script << "";
    script << "# Run comparison";
    script << "compare";
    script << "";

    if (config.extractParasitics) {
        script << "# Parasitic extraction enabled";
        script << "# extract_parasitics";
    }

    script << "";
    script << "# End of LVS script";

    return script.join("\n");
}

QString KLayoutTask::generatePEXScript(const PEXConfig& config) {
    QStringList script;

    script << "# KLayout Parasitic Extraction Script (Ruby)";
    script << "# Generated by AcuteSim";
    script << "#";
    script << QString("# Layout: %1").arg(config.layoutFile);
    script << "";

    // Script header
    script << "# Load the layout";
    script << "source($layout)";
    script << "";

    script << "# ============================================================";
    script << "# EXTRACTION CONFIGURATION";
    script << "# ============================================================";
    script << "";

    if (config.minResistance > 0) {
        script << QString("# Minimum resistance threshold: %1 ohms").arg(config.minResistance);
    }

    if (config.minCapacitance > 0) {
        script << QString("# Minimum capacitance threshold: %1 fF").arg(config.minCapacitance);
    }

    script << "";
    script << "# Layer definitions for RC extraction";
    script << "metal1 = input(11, 0)";
    script << "metal2 = input(21, 0)";
    script << "via1 = input(12, 0)";
    script << "";

    script << "# ============================================================";
    script << "# PARASITIC EXTRACTION";
    script << "# ============================================================";
    script << "";

    if (config.couplingCaps) {
        script << "# Include coupling capacitances";
        script << "# extract_coupling(true)";
    } else {
        script << "# Coupling capacitances disabled";
        script << "# extract_coupling(false)";
    }

    script << "";
    script << "# Extract parasitics";
    script << "# extract";
    script << "";

    // Output files
    if (!config.outputSpef.isEmpty()) {
        script << QString("# Write SPEF output: %1").arg(config.outputSpef);
        script << QString("# write_spef(\"%1\")").arg(config.outputSpef);
    }

    if (!config.outputSpice.isEmpty()) {
        script << QString("# Write SPICE output: %1").arg(config.outputSpice);
        script << QString("# write_spice(\"%1\")").arg(config.outputSpice);
    }

    script << "";
    script << "# End of PEX script";

    return script.join("\n");
}

QString KLayoutTask::generateBatchCommand(const QString& scriptPath) {
    // Generate command line for running KLayout in batch mode
    return QString("klayout -b -r %1").arg(scriptPath);
}

QString KLayoutTask::getDRCLevelFilter(DRCLevel level) {
    switch (level) {
        case DRCLevel::ERROR:
            return "error";
        case DRCLevel::WARNING:
            return "warning";
        case DRCLevel::INFO:
            return "info";
        default:
            return "error";
    }
}

QString KLayoutTask::getLVSModeOptions(LVSMode mode) {
    switch (mode) {
        case LVSMode::FLAT:
            return "flat";
        case LVSMode::HIERARCHICAL:
            return "deep";
        case LVSMode::DEVICE_LEVEL:
            return "deep\ndevice_level";
        default:
            return "deep";
    }
}

