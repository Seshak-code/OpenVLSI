    // ---- The waveform viewer
    const auto waveforms = [s, sh](const QJsonObject& a) -> WaveformViewer* {
        const cmd::Result r = s->call("waveform_open", {{"run", a["run"]}});
        if (!r.ok) refuse(r.error);
        for (WaveformViewer* w : sh->ciw()->findChildren<WaveformViewer*>())
            if (w->run().endsWith(a["run"].toString()) || a["run"].toString().endsWith(w->run())) return w;
        refuse("no viewer on that run");
    };
